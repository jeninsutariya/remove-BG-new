import UIKit

enum AppColor {
    static let primaryText = UIColor(named: "PrimaryText") ?? .black
    static let secondaryText = UIColor(named: "SecondaryText") ?? .darkGray
    static let background = UIColor(named: "Background") ?? .white
    static let surfaceColor = UIColor(named: "Surface Color") ?? .white
    static let borderColor = UIColor(named: "Border Color") ?? .lightGray
    static let linkColor = UIColor(named: "Link Color") ?? .blue
    static let brandPrimary = UIColor(named: "BrandPrimary") ?? .systemBlue
    static let lightBlue = UIColor(named: "Light blue") ?? .systemBlue
    static let badgeColor = UIColor(named: "Badge Color") ?? .systemBlue
    static let ultraLightBlue = UIColor(named: "Ultra Light Blue") ?? .ultraLightBlue
    static let textMuted = UIColor(named: "Text Muted") ?? .textMuted
    static let surfaceRaised = UIColor(named: "Surface Raised") ?? .surfaceRaised
    static let selected = UIColor(named: "Selected Colord") ?? .selected
    static let accent = UIColor.accent
}
